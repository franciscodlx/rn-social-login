import {
  forwardRef,
  useCallback,
  useImperativeHandle,
  useRef,
  type ReactElement,
} from 'react';
import {
  Text,
  TouchableOpacity,
  type StyleProp,
  type ViewStyle,
} from 'react-native';
import {
  cancelAuthorize,
  toAuthError,
  type ProviderLogin,
} from '@franciscodlxdev/rn-auth-core';
import { linkedInLogin, type LinkedInProfile } from './provider';

/** @deprecated Shape kept from `@gcou/react-native-linkedin`. */
export interface LinkedInToken {
  authentication_code?: string;
  access_token?: string;
  expires_in?: number;
}

/** @deprecated Shape kept from `@gcou/react-native-linkedin`. */
export interface ErrorType {
  type?: string;
  message?: string;
}

export interface LinkedInModalRef {
  open: () => void;
  close: () => void;
  /** No-op: the system browser owns the LinkedIn session, the app cannot clear it. */
  logoutAsync: () => Promise<void>;
}

export interface LinkedInModalPropTypes {
  clientID: string;
  redirectUri: string;
  /** New: app URL the browser lands on when `redirectUri` is a page on your backend. */
  callbackUri?: string;
  onSuccess: (result: LinkedInToken) => void;
  onError?: (error: ErrorType) => void;
  onOpen?: () => void;
  onClose?: () => void;
  onSignIn?: () => void;
  permissions?: string[];
  renderButton?: () => ReactElement;
  linkText?: string;
  isDisabled?: boolean;
  areaTouchText?: {
    top?: number;
    bottom?: number;
    left?: number;
    right?: number;
  };
  /** No longer supported: the secret must stay on your backend. */
  clientSecret?: string;
  /** No longer supported: the component always returns the authorization code. */
  shouldGetAccessToken?: boolean;
  /** Ignored: `state` is generated by the library. */
  authState?: string;
  /** Ignored: there is no modal any more, sign-in opens the system browser. */
  renderClose?: () => ReactElement;
  /** Ignored, see `renderClose`. */
  containerStyle?: StyleProp<ViewStyle>;
  /** Ignored, see `renderClose`. */
  wrapperStyle?: StyleProp<ViewStyle>;
  /** Ignored, see `renderClose`. */
  closeStyle?: StyleProp<ViewStyle>;
  /** Ignored, see `renderClose`. */
  animationType?: 'none' | 'fade' | 'slide';
  /** New: use another login instance (tests, staging). */
  login?: ProviderLogin<LinkedInProfile>;
}

const warned = new Set<string>();
function warnOnce(key: string, message: string) {
  if (!warned.has(key)) {
    warned.add(key);
    console.warn(`[react-native-linkedin-login] ${message}`);
  }
}

const DEFAULT_HIT_SLOP = { top: 20, bottom: 20, left: 50, right: 50 };

/**
 * Drop-in replacement for the `LinkedInModal` of `@gcou/react-native-linkedin`.
 * It keeps the props and the ref API, but signs in through the system browser
 * instead of a WebView in a Modal.
 *
 * @deprecated Use `useLinkedInLogin()` or `linkedInLogin.signIn()`.
 */
const LinkedInModal = forwardRef<LinkedInModalRef, LinkedInModalPropTypes>(
  function LinkedInLoginButton(props, ref) {
    const latest = useRef(props);
    latest.current = props;

    const open = useCallback(async () => {
      const p = latest.current;
      warnOnce(
        'component',
        'LinkedInModal is deprecated. Use useLinkedInLogin() instead.'
      );
      if (p.clientSecret || p.shouldGetAccessToken) {
        warnOnce(
          'secret',
          'clientSecret / shouldGetAccessToken are no longer supported. onSuccess receives { authentication_code }; exchange it on your backend.'
        );
      }
      p.onOpen?.();
      try {
        const result = await (p.login ?? linkedInLogin).signIn({
          clientId: p.clientID,
          redirectUri: p.redirectUri,
          callbackUri: p.callbackUri,
          // The old default (r_liteprofile, r_emailaddress) was retired by LinkedIn.
          scopes: p.permissions,
        });
        latest.current.onSignIn?.();
        latest.current.onSuccess({ authentication_code: result.code });
      } catch (e) {
        const error = toAuthError(e);
        if (error.code !== 'CANCELLED') {
          const report = latest.current.onError ?? logError;
          report({
            type: error.providerError ?? error.code.toLowerCase(),
            message: error.message,
          });
        }
      } finally {
        latest.current.onClose?.();
      }
    }, []);

    useImperativeHandle(
      ref,
      (): LinkedInModalRef => ({
        open: () => {
          open();
        },
        close: () => {
          try {
            cancelAuthorize();
          } catch {
            // Native module not linked: nothing is open.
          }
        },
        logoutAsync: async () => {
          warnOnce(
            'logout',
            'logoutAsync() is a no-op: the system browser owns the LinkedIn session.'
          );
        },
      }),
      [open]
    );

    return (
      <TouchableOpacity
        accessibilityRole="button"
        disabled={props.isDisabled}
        onPress={open}
        hitSlop={{ ...DEFAULT_HIT_SLOP, ...props.areaTouchText }}
      >
        {props.renderButton ? (
          props.renderButton()
        ) : (
          <Text>{props.linkText ?? 'Login with LinkedIn'}</Text>
        )}
      </TouchableOpacity>
    );
  }
);

LinkedInModal.displayName = 'LinkedInModal';

function logError(error: ErrorType) {
  console.error(JSON.stringify(error, null, 2));
}

export default LinkedInModal;
